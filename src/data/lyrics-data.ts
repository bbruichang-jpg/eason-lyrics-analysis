// 词云词频统计结果接口
export interface WordFrequency {
  word: string;
  count: number;
  songs: string[]; // 包含该词的歌曲ID列表
  albums: string[]; // 包含该词的专辑ID列表
}

// 歌词溯源信息接口
export interface LyricTrace {
  word: string;
  totalCount: number;
  songCount: number;
  albumCount: number;
  traces: TraceItem[];
}

export interface TraceItem {
  albumId: string;
  albumName: string;
  songId: string;
  songName: string;
  lyricSnippet: string;
}

// 分析结果接口
export interface AnalysisResult {
  totalWords: number;
  uniqueWords: number;
  songCount: number;
  wordFrequencies: WordFrequency[];
}
